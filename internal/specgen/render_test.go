// The generated wrapper must be real Go: compile it with the provider's real
// helpers (spec 2b, section 5.1).
func TestCRUDGoldenCompiles(t *testing.T) {
	dir := filepath.Join("testdata", "crudcheck")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(dir) })
	copyFile := func(src, dst string) {
		b, err := os.ReadFile(src)
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, dst), b, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	copyFile("testdata/widget_crud_resource_gen.go.golden", "widget_resource_gen.go")
	copyFile("testdata/gadget_alpha_resource_gen.go.golden", "gadget_alpha_resource_gen.go")
	for _, f := range []string{"convert.go", "nullable.go", "diagnostics.go", "import.go", "collections.go", "objects.go", "maps.go"} {
		copyFile(filepath.Join("..", "provider", f), f)
	}
	// The registry normally holds the variant names.
	variants := "package provider\n\nvar gadgetVariants = map[string]string{\"Alpha\": \"honeybadger_gadget_alpha\"}\n"
	if err := os.WriteFile(filepath.Join(dir, "variants.go"), []byte(variants), 0o644); err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command("go", "vet", "./testdata/crudcheck").CombinedOutput()
	if err != nil {
		t.Errorf("go vet ./testdata/crudcheck: %v\n%s", err, out)
	}
}

func TestRenderNestedAndCollections(t *testing.T) {
	res, err := Merge(loadFixture(t), "widget", fixtureConfig(t))
	if err != nil {
		t.Fatalf("Merge: %v", err)
	}
	got, err := Render(res, nil)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	// gofmt aligns keys and struct fields, so spacing is matched loosely.
	for _, want := range []string{
		`MarkdownDescription:\s+"A widget in a project\."`,
		`"gear": schema\.SingleNestedAttribute\{`,
		`"mesh": schema\.SingleNestedAttribute\{`,
		`setvalidator\.SizeBetween\(1, 10\)`,
		"Gear\\s+types\\.Object\\s+`tfsdk:\"gear\"`",
		`type widgetGearModel struct`,
		`type widgetGearMeshModel struct`,
		`"mesh":\s+types\.ObjectType\{AttrTypes: widgetGearMeshAttrTypes\(\)\}`,
		`"parts": schema\.SetAttribute\{`,
	} {
		if !regexp.MustCompile(want).Match(got) {
			t.Errorf("rendered code doesn't match %s", want)
		}
	}
}

