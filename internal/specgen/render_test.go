var update = flag.Bool("update", false, "rewrite golden files")

func TestRenderMatchesGolden(t *testing.T) {
	res, err := Merge(loadFixture(t), "widget", fixtureConfig(t))
	if err != nil {
		t.Fatalf("Merge: %v", err)
	}
	got, err := Render(res, nil)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	golden := "testdata/compile/widget_resource_gen.go"
	if *update {
		if err := os.WriteFile(golden, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("reading golden (run with -update to create it): %v", err)
	}
	if string(got) != string(want) {
		t.Errorf("rendered code differs from %s; rerun with -update and review the diff", golden)
	}
}

