package specgen

import (
	"flag"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	// The golden output imports these. Only testdata uses them until 2b's
	// generated resources do, and go mod tidy ignores testdata, so these keep
	// them in go.mod for TestGoldenCompiles.
	_ "github.com/hashicorp/terraform-plugin-framework-validators/int64validator"
	_ "github.com/hashicorp/terraform-plugin-framework-validators/stringvalidator"
)

var update = flag.Bool("update", false, "rewrite golden files")

func TestRenderMatchesGolden(t *testing.T) {
	res, err := Merge(loadFixture(t), "widget", fixtureConfig(t))
	if err != nil {
		t.Fatalf("Merge: %v", err)
	}
	got, err := Render(res)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	golden := "testdata/compile/widget_resource_gen.go"
	if *update {
		if err := os.WriteFile(golden, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("reading golden (run with -update to create it): %v", err)
	}
	if string(got) != string(want) {
		t.Errorf("rendered code differs from %s; rerun with -update and review the diff", golden)
	}
}

// The golden output must be real Go: it's type-checked as a package.
func TestGoldenCompiles(t *testing.T) {
	out, err := exec.Command("go", "vet", "./testdata/compile").CombinedOutput()
	if err != nil {
		t.Errorf("go vet ./testdata/compile: %v\n%s", err, out)
	}
}

// Review Focus 3: a resource removed from the config loses its generated file.
func TestGenerateRemovesStaleFiles(t *testing.T) {
	dir := t.TempDir()
	stale := filepath.Join(dir, "gizmo_resource_gen.go")
	keep := filepath.Join(dir, "provider.go")
	for _, f := range []string{stale, keep} {
		if err := os.WriteFile(f, []byte("package provider\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := Generate("testdata/openapi.yaml", "testdata/resources.yaml", dir); err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Error("stale gizmo_resource_gen.go wasn't removed")
	}
	if _, err := os.Stat(keep); err != nil {
		t.Error("a hand-written file was touched")
	}
	got, err := os.ReadFile(filepath.Join(dir, "widget_resource_gen.go"))
	if err != nil {
		t.Fatalf("widget_resource_gen.go wasn't written: %v", err)
	}
	if !strings.HasPrefix(string(got), "// Code generated by specgen. DO NOT EDIT.") {
		t.Error("generated file lacks the generated-code header")
	}
}
