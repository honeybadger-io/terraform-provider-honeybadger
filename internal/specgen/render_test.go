// A committed generated resource can't disappear unless resources.yaml
// retires it (phase 4b spec, 3.6).
func TestGenerateRefusesToDropAResource(t *testing.T) {
	dir := t.TempDir()
	stale := filepath.Join(dir, "gizmo_resource_gen.go")
	if err := os.WriteFile(stale, []byte("package provider\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	err := Generate("testdata/openapi.yaml", "testdata/resources.yaml", dir, "")
	if err == nil || !strings.Contains(err.Error(), "gizmo") || !strings.Contains(err.Error(), "retired") {
		t.Fatalf("err = %v, want one naming gizmo and retired", err)
	}
	if _, err := os.Stat(stale); err != nil {
		t.Error("the file was removed despite the error")
	}
}

func TestGenerateRemovesRetiredFiles(t *testing.T) {
	dir := t.TempDir()
	stale := filepath.Join(dir, "gizmo_resource_gen.go")
	if err := os.WriteFile(stale, []byte("package provider\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	cfg := filepath.Join(dir, "resources.yaml")
	b, _ := os.ReadFile("testdata/resources.yaml")
	if err := os.WriteFile(cfg, append(b, []byte("retired: [gizmo]\n")...), 0o644); err != nil {
		t.Fatal(err)
	}
	keep := filepath.Join(dir, "provider.go")
	if err := os.WriteFile(keep, []byte("package provider\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := Generate("testdata/openapi.yaml", cfg, dir, ""); err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Error("retired gizmo wasn't removed")
	}
	if _, err := os.Stat(keep); err != nil {
		t.Error("a hand-written file was touched")
	}
	got, err := os.ReadFile(filepath.Join(dir, "widget_resource_gen.go"))
	if err != nil || !strings.HasPrefix(string(got), "// Code generated by specgen. DO NOT EDIT.") {
		t.Errorf("widget_resource_gen.go missing or lacks the header: %v", err)
	}
}

// A validator's message is shown to users on every bad value, so it describes
// the format rather than printing a long regex.
func TestPatternMessages(t *testing.T) {
	long := `^(\d+ (second|minute|hour|day|week|month|year)s?)( \d+ (second|minute|hour|day|week|month|year)s?)*$|^\d\d:\d\d:\d\d$`
	tests := []struct {
		name string
		attr Attribute
		want string
	}{
		{"custom type", Attribute{Name: "grace_period", Kind: "string", Pattern: long, CustomType: "period"},
			`must be a period such as \"5 minutes\", \"1 hour 30 minutes\" or \"01:30:00\"`},
		{"short pattern", Attribute{Name: "color", Kind: "string", Pattern: "^#[0-9a-f]{6}$"},
			`must match ^#[0-9a-f]{6}$`},
		{"long pattern", Attribute{Name: "code", Kind: "string", Pattern: long},
			`isn't in the format the Honeybadger API accepts; see the attribute's description`},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			src, err := Render(Resource{Name: "widget", Attributes: []Attribute{tt.attr}}, nil)
			if err != nil {
				t.Fatalf("Render: %v", err)
			}
			if !strings.Contains(string(src), tt.want) {
				t.Errorf("rendered code doesn't contain %s:\n%s", tt.want, src)
			}
		})
	}
}

